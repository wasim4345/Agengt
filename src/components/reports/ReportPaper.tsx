"use client";

import type { BuiltReport } from "@/selectors/reports";
import { formatINR } from "@/lib/format/inr";
import { formatDate } from "@/lib/format/dates";
import { Badge } from "@/components/ui";

const MONEY_KEYS = new Set([
  "approved",
  "reported",
  "verified",
  "pending",
  "unallocated",
  "revised",
  "totalBudget",
  "verifiedExpenditure",
  "reportedExpenditure",
  "remaining",
  "closureSurplus",
]);

function formatCell(key: string, value: string | number | null | undefined) {
  if (value == null) return "—";
  if (typeof value === "number" && MONEY_KEYS.has(key)) return formatINR(value);
  if (key === "progress" || key === "percentComplete" || key === "overallProgress") {
    return `${value}%`;
  }
  return String(value);
}

export function ReportPaper({ report }: { report: BuiltReport }) {
  const clientSections = report.sections as
    | {
        overview?: { code: string; name: string; objectives: string; progress: number }[];
        milestones?: { name: string; targetDate: string; health: string }[];
        reports?: { clientSummary: string; keyOutcomes: string; type: string }[];
        outputs?: { keyOutcomes: string }[];
        programme?: { code: string; name: string; status: string } | null;
        closure?: { ready: boolean; issues: string[] };
      }
    | undefined;

  return (
    <article
      id="report-paper"
      className="report-paper mx-auto w-full max-w-[210mm] rounded-sm border border-border bg-white p-8 text-foreground shadow-sm"
    >
      <header className="mb-6 border-b border-border pb-4">
        <p className="text-xs uppercase tracking-wide text-muted">
          IIMCIP Programme Management OS
        </p>
        <h2 className="mt-1 text-xl font-semibold text-primary">
          {report.title}
        </h2>
        <p className="mt-2 text-sm text-muted">
          Data as of {formatDate(report.dataAsOf)} · Generated by{" "}
          {report.generatedBy} ({report.role})
        </p>
      </header>

      {report.error ? (
        <p className="text-sm text-danger">{report.error}</p>
      ) : null}

      {report.totals ? (
        <section className="mb-6">
          <h3 className="mb-2 text-sm font-semibold">Totals</h3>
          <div className="grid gap-2 sm:grid-cols-2 lg:grid-cols-3">
            {Object.entries(report.totals).map(([key, value]) => (
              <div
                key={key}
                className="rounded-md border border-border bg-background px-3 py-2"
              >
                <p className="text-xs text-muted">{key}</p>
                <p className="text-sm font-medium">
                  {formatCell(key, value)}
                </p>
              </div>
            ))}
          </div>
        </section>
      ) : null}

      {clientSections?.programme ? (
        <section className="mb-4 text-sm">
          <p>
            <span className="font-medium">
              {clientSections.programme.code}
            </span>{" "}
            · {clientSections.programme.name}{" "}
            <Badge tone="neutral">{clientSections.programme.status}</Badge>
          </p>
        </section>
      ) : null}

      {clientSections?.closure ? (
        <section className="mb-4 text-sm">
          <Badge
            tone={clientSections.closure.ready ? "on-track" : "delayed"}
          >
            {clientSections.closure.ready
              ? "Ready for closure"
              : "Not ready"}
          </Badge>
          {clientSections.closure.issues.length > 0 ? (
            <ul className="mt-2 list-disc pl-5 text-danger">
              {clientSections.closure.issues.map((i) => (
                <li key={i}>{i}</li>
              ))}
            </ul>
          ) : null}
        </section>
      ) : null}

      {clientSections?.overview && report.id === "client_programme" ? (
        <section className="mb-6">
          <h3 className="mb-2 text-sm font-semibold">Programmes</h3>
          {clientSections.overview.map((p) => (
            <div key={p.code} className="mb-3 text-sm">
              <p className="font-medium">
                {p.code} · {p.name} · {Math.round(p.progress)}%
              </p>
              <p className="text-muted">{p.objectives}</p>
            </div>
          ))}
        </section>
      ) : null}

      {clientSections?.milestones && report.id === "client_programme" ? (
        <section className="mb-6">
          <h3 className="mb-2 text-sm font-semibold">Milestones</h3>
          <ul className="list-disc pl-5 text-sm">
            {clientSections.milestones.map((m) => (
              <li key={`${m.name}-${m.targetDate}`}>
                {m.name} — {formatDate(m.targetDate)} ({m.health})
              </li>
            ))}
          </ul>
        </section>
      ) : null}

      {clientSections?.reports && report.id === "client_programme" ? (
        <section className="mb-6">
          <h3 className="mb-2 text-sm font-semibold">Released reports</h3>
          {clientSections.reports.map((r, i) => (
            <div key={i} className="mb-3 border-b border-border pb-2 text-sm">
              <p className="font-medium">{r.type}</p>
              <p>{r.clientSummary}</p>
              <p className="text-muted">{r.keyOutcomes}</p>
            </div>
          ))}
        </section>
      ) : null}

      {report.columns && report.rows && report.rows.length > 0 ? (
        <section className="report-table-section">
          <h3 className="mb-2 text-sm font-semibold">Detail</h3>
          <div className="overflow-x-auto">
            <table className="w-full border-collapse text-left text-xs">
              <thead>
                <tr className="border-b border-border">
                  {report.columns.map((c) => (
                    <th key={c} className="px-2 py-1.5 font-semibold">
                      {c}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {report.rows.map((row, i) => (
                  <tr key={i} className="border-b border-border/70">
                    {report.columns!.map((c) => (
                      <td key={c} className="px-2 py-1.5">
                        {formatCell(c, row[c])}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>
      ) : null}

      {!report.error && (!report.rows || report.rows.length === 0) && !clientSections?.overview ? (
        <p className="text-sm text-muted">No rows for the selected parameters.</p>
      ) : null}

      <footer className="mt-8 border-t border-border pt-3 text-xs text-muted">
        Confidential prototype export · Data as of {formatDate(report.dataAsOf)}
      </footer>
    </article>
  );
}
